  /** タブに出す名前（日本語）。 */
  label: string
  /** ✕ を出すか。⚠ 「本文」は常にあるタブなので閉じられない（§1-9-2）。 */
  closable?: boolean
  /** 未保存の印（`●`）を出すか。⚠ 「隠れているだけ」を目で見せるための印（§1-9-2）。 */
  dirty?: boolean
